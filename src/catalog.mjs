export const degreeLevels={bachelor:{label:'学士',short:'本科'},master:{label:'硕士',short:'硕士'},doctor:{label:'博士',short:'博士'}};
export const degreeCategories={academic:{label:'学术学位'},professional:{label:'专业学位'}};

// 每个门类下可选的专业组：{label, majors:[{code?,name}]}。
export function majorGroups(level,category,categoryCode){
 if(level==='bachelor')return bachelor.filter(([code])=>code.startsWith(categoryCode)).map(([code,name,list])=>({code,label:name,majors:list.split(' ').map(n=>({name:n}))}));
 if(category==='academic'){const list=academic[categoryCode];return list?[{label:'一级学科',majors:pairs(list).map(({code,name})=>({code,name}))}]:[];}
 const list=professional[categoryCode];if(!list)return [];
 const majors=pairs(list).filter(m=>level!=='doctor'||m.doctor).map(({code,name})=>({code,name}));
 return majors.length?[{label:'专业学位类别',majors}]:[];
}
// 某学位层次与类型下可选的学科门类（本科目录不含军事学、交叉学科门类）。
export function availableCategories(level,category){return categories.filter(c=>majorGroups(level,category,c.code).length);}
export function findMajor(level,category,categoryCode,name){return majorGroups(level,category,categoryCode).flatMap(g=>g.majors).find(m=>m.name===name)||null;}
export function catalogPayload(){
 const tree={};
 for(const level of Object.keys(degreeLevels))for(const category of Object.keys(degreeCategories)){tree[`${category}_${level}`]=Object.fromEntries(availableCategories(level,category).map(c=>[c.code,majorGroups(level,category,c.code)]));}
 return {categories,levels:degreeLevels,degree_categories:degreeCategories,tree,sources:['研究生教育学科专业目录（2022 年）','普通高等学校本科专业目录（2025 年）']};
}
